//! The one-time move of a version-1 home (`~/.tx-core`, everything in one directory) into the
//! five XDG directories. Records are moved as they are; upgrading them is a later step.
//!
//! The move refuses, before touching anything, while the old home's tmux server has sessions
//! (their agents still carry the old paths), when the old home was already moved, and when any
//! destination is occupied, so two homes are never merged.

use std::io;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::config::{AGENTS_DIR, CONF_FILE, Directories, SOCKET_FILE};
use crate::core::{DEFAULT_TMUX_CONF, SESSIONS_DIR, TMUX_BINARY};
use crate::events::now;

/// Left in the old home after a move: where everything went.
pub const MOVED_TO_FILE: &str = "MOVED-TO";
/// Written into the data directory after a move: where everything came from.
pub const MIGRATED_FROM_FILE: &str = "MIGRATED-FROM";

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
enum Destination {
    Config,
    Data,
    State,
}

/// Every entry of a version-1 home that moves, with the directory and name it moves to. The
/// shipped roles (`agents/`, generated by `ui install`) go to data; the user's own to config.
const MAPPING: [(&str, Destination, &str); 11] = [
    ("agents", Destination::Data, "roles"),
    ("user-agents", Destination::Config, "roles"),
    ("plugins.yaml", Destination::Config, "plugins.yaml"),
    (SESSIONS_DIR, Destination::Data, SESSIONS_DIR),
    ("log.jsonl", Destination::Data, "log.jsonl"),
    ("plugins", Destination::Data, "plugins"),
    ("bin", Destination::Data, "bin"),
    ("keys", Destination::Data, "keys"),
    ("conf", Destination::Data, "conf"),
    (CONF_FILE, Destination::Data, CONF_FILE),
    ("profiles", Destination::State, "profiles"),
];

#[derive(Debug, Default, PartialEq, Eq)]
pub struct MigrationReport {
    /// `(from, to)`, in mapping order.
    pub moved: Vec<(PathBuf, PathBuf)>,
    /// Entries left in the old home: `locks/`, the socket, and anything the mapping does not
    /// know.
    pub left: Vec<PathBuf>,
}

#[derive(Debug, thiserror::Error)]
pub enum MigrationError {
    #[error("{} is not a version-1 home (it has no sessions/)", .0.display())]
    NotAHome(PathBuf),
    #[error("{} was already moved; see {}", .0.display(), .0.join(MOVED_TO_FILE).display())]
    AlreadyMoved(PathBuf),
    #[error("the tmux server at {} still has sessions: {}; stop these first", .socket.display(), .sessions.join(", "))]
    LiveSessions {
        socket: PathBuf,
        sessions: Vec<String>,
    },
    #[error("refusing to merge two homes; these already exist: {}", .0.iter().map(|path| path.display().to_string()).collect::<Vec<_>>().join(", "))]
    Occupied(Vec<PathBuf>),
    #[error("{}: {source}", .path.display())]
    Io { path: PathBuf, source: io::Error },
}

fn io_error(path: &Path) -> impl FnOnce(io::Error) -> MigrationError + '_ {
    move |source| MigrationError::Io {
        path: path.to_owned(),
        source,
    }
}

fn target(directories: &Directories, destination: Destination) -> &Path {
    match destination {
        Destination::Config => &directories.config,
        Destination::Data => &directories.data,
        Destination::State => &directories.state,
    }
}

/// Moves the version-1 home `old_home` into `directories`, per [`MAPPING`].
pub fn migrate_home(
    old_home: &Path,
    directories: &Directories,
) -> Result<MigrationReport, MigrationError> {
    if old_home.join(MOVED_TO_FILE).exists() {
        return Err(MigrationError::AlreadyMoved(old_home.to_owned()));
    }
    if !old_home.join(SESSIONS_DIR).is_dir() {
        return Err(MigrationError::NotAHome(old_home.to_owned()));
    }
    let socket = old_home.join(SOCKET_FILE);
    let sessions = live_sessions(&socket)?;
    if !sessions.is_empty() {
        return Err(MigrationError::LiveSessions { socket, sessions });
    }

    let moves: Vec<(PathBuf, PathBuf)> = MAPPING
        .iter()
        .map(|(name, destination, new_name)| {
            (
                old_home.join(name),
                target(directories, *destination).join(new_name),
            )
        })
        .filter(|(from, _)| from.symlink_metadata().is_ok())
        .collect();
    let mut occupied = Vec::new();
    // The agent records of a later version live here; a home that has them was set up anew.
    let agents = directories.data.join(AGENTS_DIR);
    if agents.symlink_metadata().is_ok() {
        occupied.push(agents);
    }
    for (_, to) in &moves {
        if is_occupied(to)? {
            occupied.push(to.clone());
        }
    }
    if !occupied.is_empty() {
        return Err(MigrationError::Occupied(occupied));
    }

    let mut report = MigrationReport::default();
    for (from, to) in moves {
        clear_free_destination(&to)?;
        let parent = to
            .parent()
            .expect("a destination is a directory joined with a name");
        std::fs::create_dir_all(parent).map_err(io_error(parent))?;
        move_entry(&from, &to)?;
        report.moved.push((from, to));
    }
    let mut left: Vec<PathBuf> = std::fs::read_dir(old_home)
        .map_err(io_error(old_home))?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<_, _>>()
        .map_err(io_error(old_home))?;
    left.sort();
    report.left = left;

    let at = now();
    let migrated_from = directories.data.join(MIGRATED_FROM_FILE);
    std::fs::create_dir_all(&directories.data).map_err(io_error(&directories.data))?;
    std::fs::write(
        &migrated_from,
        format!("from: {}\nat: {at}\n", old_home.display()),
    )
    .map_err(io_error(&migrated_from))?;
    let mut moved_to = String::new();
    for (key, directory) in directories.environment() {
        moved_to.push_str(&format!("{key}={}\n", directory.display()));
    }
    moved_to.push_str(&format!("at: {at}\n"));
    let moved_to_path = old_home.join(MOVED_TO_FILE);
    std::fs::write(&moved_to_path, moved_to).map_err(io_error(&moved_to_path))?;
    Ok(report)
}

/// The session names on the tmux server behind `socket`; none when no server answers there.
fn live_sessions(socket: &Path) -> Result<Vec<String>, MigrationError> {
    if socket.symlink_metadata().is_err() {
        return Ok(Vec::new());
    }
    let output = Command::new(TMUX_BINARY)
        .arg("-S")
        .arg(socket)
        .args(["list-sessions", "-F", "#{session_name}"])
        .output()
        .map_err(io_error(Path::new(TMUX_BINARY)))?;
    if !output.status.success() {
        return Ok(Vec::new());
    }
    Ok(String::from_utf8_lossy(&output.stdout)
        .lines()
        .map(str::to_owned)
        .collect())
}

/// A destination is free when it is absent, an empty directory, or the default `tmux.conf`
/// `TxCore::open` writes.
fn is_occupied(path: &Path) -> Result<bool, MigrationError> {
    let Ok(metadata) = path.symlink_metadata() else {
        return Ok(false);
    };
    if metadata.is_dir() {
        let mut entries = std::fs::read_dir(path).map_err(io_error(path))?;
        return Ok(entries.next().is_some());
    }
    if path.file_name().is_some_and(|name| name == CONF_FILE) {
        let text = std::fs::read_to_string(path).map_err(io_error(path))?;
        return Ok(text != DEFAULT_TMUX_CONF);
    }
    Ok(true)
}

fn clear_free_destination(path: &Path) -> Result<(), MigrationError> {
    let Ok(metadata) = path.symlink_metadata() else {
        return Ok(());
    };
    if metadata.is_dir() {
        std::fs::remove_dir(path).map_err(io_error(path))
    } else {
        std::fs::remove_file(path).map_err(io_error(path))
    }
}

/// `rename` within a filesystem; copy, then delete, across filesystems.
fn move_entry(from: &Path, to: &Path) -> Result<(), MigrationError> {
    match std::fs::rename(from, to) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == io::ErrorKind::CrossesDevices => {
            copy_entry(from, to)?;
            remove_entry(from)
        }
        Err(error) => Err(io_error(from)(error)),
    }
}

fn copy_entry(from: &Path, to: &Path) -> Result<(), MigrationError> {
    let metadata = from.symlink_metadata().map_err(io_error(from))?;
    if metadata.is_symlink() {
        let link = std::fs::read_link(from).map_err(io_error(from))?;
        std::os::unix::fs::symlink(link, to).map_err(io_error(to))
    } else if metadata.is_dir() {
        std::fs::create_dir(to).map_err(io_error(to))?;
        std::fs::set_permissions(to, metadata.permissions()).map_err(io_error(to))?;
        for entry in std::fs::read_dir(from).map_err(io_error(from))? {
            let entry = entry.map_err(io_error(from))?;
            copy_entry(&entry.path(), &to.join(entry.file_name()))?;
        }
        Ok(())
    } else {
        std::fs::copy(from, to).map_err(io_error(from))?;
        Ok(())
    }
}

fn remove_entry(path: &Path) -> Result<(), MigrationError> {
    if path.symlink_metadata().map_err(io_error(path))?.is_dir() {
        std::fs::remove_dir_all(path).map_err(io_error(path))
    } else {
        std::fs::remove_file(path).map_err(io_error(path))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn write(path: &Path, text: &str) {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(path, text).unwrap();
    }

    /// A version-1 home with one entry of every kind the mapping knows, plus one it does not.
    fn version_one_home(root: &Path) -> PathBuf {
        let old = root.join("old");
        write(&old.join("sessions/a.json"), "{}");
        write(&old.join("log.jsonl"), "{}\n");
        write(&old.join("plugins.yaml"), "chat: true\n");
        write(&old.join("agents/COMMON.md"), "shipped");
        write(&old.join("user-agents/MINE.md"), "mine");
        write(&old.join("plugins/artifacts/x.json"), "{}");
        write(&old.join("bin/tmux-nav"), "#!/bin/sh");
        write(&old.join("keys/ide.tmux"), "");
        write(&old.join("conf/tmux.conf"), "");
        write(&old.join("tmux.conf"), "generated");
        write(&old.join("profiles/a.md"), "role");
        write(&old.join("locks/create.lock"), "");
        write(&old.join("unknown.txt"), "?");
        old
    }

    #[test]
    fn moves_every_entry_per_the_mapping_and_refuses_a_second_run() {
        let root = tempfile::tempdir().unwrap();
        let old = version_one_home(root.path());
        let directories = Directories::under(root.path().join("new"));
        let report = migrate_home(&old, &directories).unwrap();
        for (path, text) in [
            (directories.data.join("roles/COMMON.md"), "shipped"),
            (directories.config.join("roles/MINE.md"), "mine"),
            (directories.config.join("plugins.yaml"), "chat: true\n"),
            (directories.data.join("sessions/a.json"), "{}"),
            (directories.data.join("log.jsonl"), "{}\n"),
            (directories.data.join("plugins/artifacts/x.json"), "{}"),
            (directories.data.join("bin/tmux-nav"), "#!/bin/sh"),
            (directories.data.join("tmux.conf"), "generated"),
            (directories.state.join("profiles/a.md"), "role"),
        ] {
            assert_eq!(std::fs::read_to_string(&path).unwrap(), text, "{path:?}");
        }
        assert_eq!(report.moved.len(), MAPPING.len());
        assert_eq!(report.left, [old.join("locks"), old.join("unknown.txt")]);
        assert!(!old.join("sessions").exists());
        assert!(!directories.state.join("locks").exists());
        let moved_to = std::fs::read_to_string(old.join(MOVED_TO_FILE)).unwrap();
        assert!(
            moved_to.contains(&format!("TX_DATA_DIR={}", directories.data.display())),
            "{moved_to}"
        );
        let migrated_from =
            std::fs::read_to_string(directories.data.join(MIGRATED_FROM_FILE)).unwrap();
        assert!(migrated_from.contains(&old.display().to_string()));

        let again = migrate_home(&old, &directories).unwrap_err();
        assert!(matches!(again, MigrationError::AlreadyMoved(_)), "{again}");
    }

    #[test]
    fn an_opened_but_empty_new_home_is_free() {
        let root = tempfile::tempdir().unwrap();
        let old = version_one_home(root.path());
        let directories = Directories::under(root.path().join("new"));
        std::fs::create_dir_all(directories.data.join("sessions")).unwrap();
        write(&directories.data.join("tmux.conf"), DEFAULT_TMUX_CONF);
        migrate_home(&old, &directories).unwrap();
        assert_eq!(
            std::fs::read_to_string(directories.data.join("tmux.conf")).unwrap(),
            "generated"
        );
    }

    #[test]
    fn refuses_to_merge_into_an_occupied_home_and_touches_nothing() {
        let root = tempfile::tempdir().unwrap();
        let old = version_one_home(root.path());
        let directories = Directories::under(root.path().join("new"));
        write(&directories.data.join("sessions/b.json"), "{}");
        std::fs::create_dir_all(directories.data.join("agents")).unwrap();
        let error = migrate_home(&old, &directories).unwrap_err();
        let MigrationError::Occupied(paths) = &error else {
            panic!("{error:?}")
        };
        assert_eq!(
            *paths,
            [
                directories.data.join("agents"),
                directories.data.join("sessions")
            ]
        );
        assert!(old.join("sessions/a.json").exists());
        assert!(!old.join(MOVED_TO_FILE).exists());
    }

    #[test]
    fn refuses_a_directory_that_is_not_a_home() {
        let root = tempfile::tempdir().unwrap();
        let error =
            migrate_home(root.path(), &Directories::under(root.path().join("new"))).unwrap_err();
        assert!(matches!(error, MigrationError::NotAHome(_)), "{error}");
    }

    #[test]
    fn copies_a_tree_with_its_modes() {
        use std::os::unix::fs::PermissionsExt;
        let root = tempfile::tempdir().unwrap();
        let from = root.path().join("from");
        write(&from.join("bin/script"), "x");
        std::fs::set_permissions(
            from.join("bin/script"),
            std::fs::Permissions::from_mode(0o755),
        )
        .unwrap();
        std::os::unix::fs::symlink("bin/script", from.join("link")).unwrap();
        let to = root.path().join("to");
        copy_entry(&from, &to).unwrap();
        remove_entry(&from).unwrap();
        let mode = std::fs::metadata(to.join("bin/script"))
            .unwrap()
            .permissions()
            .mode();
        assert_eq!(mode & 0o777, 0o755);
        assert_eq!(
            std::fs::read_link(to.join("link")).unwrap(),
            Path::new("bin/script")
        );
        assert!(!from.exists());
    }
}
